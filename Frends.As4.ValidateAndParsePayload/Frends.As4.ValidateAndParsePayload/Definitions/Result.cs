namespace Frends.As4.ValidateAndParsePayload.Definitions;

/// <summary>
/// Result of the task.
/// </summary>
public class Result
{
    /// <summary>
    /// Indicates if the task completed successfully.
    /// </summary>
    /// <example>true</example>
    public bool Success { get; set; }

    /// <summary>
    /// Decrypted/decompressed business data (EDI/XML/JSON) extracted from the first AS4 payload.
    /// </summary>
    /// <example>This is a nice test message :)</example>
    public string Payload { get; set; }

    /// <summary>
    /// AS4 sender party identifier.
    /// </summary>
    /// <example>PartnerAS4</example>
    public string As4From { get; set; }

    /// <summary>
    /// AS4 receiver party identifier.
    /// </summary>
    /// <example>MyCompanyAS4</example>
    public string As4To { get; set; }

    /// <summary>
    /// ID of the received ebMS message.
    /// </summary>
    /// <example>"123456789@example.com"</example>
    public string MessageId { get; set; }

    /// <summary>
    /// Receipt generated by the AS4Server. To be used later when sending the AS4 receipt response.
    /// </summary>
    /// <example>object { "Content": "...", "RefToMessageId": "..." }</example>
    public ReceiptData Receipt { get; set; }

    /// <summary>
    /// Error that occurred during task execution.
    /// </summary>
    /// <example>object { string Message, Exception AdditionalInfo }</example>
    public Error Error { get; set; }
}
